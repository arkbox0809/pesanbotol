-- Migrasi: Tabel antrian notifikasi dan langganan push
-- Digunakan untuk notifikasi balasan pesan (maksimal 1 push per hari per perangkat)

CREATE TABLE IF NOT EXISTS public.notification_queue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_token text NOT NULL,
  target_bottle_id bigint NOT NULL REFERENCES public.bottles(id) ON DELETE CASCADE,
  content text NOT NULL,
  created_at timestamptz DEFAULT now() NOT NULL,
  is_read boolean DEFAULT false NOT NULL
);

CREATE INDEX IF NOT EXISTS notification_queue_device_token_created_at_idx
  ON public.notification_queue (device_token, created_at DESC);

CREATE INDEX IF NOT EXISTS notification_queue_device_token_is_read_idx
  ON public.notification_queue (device_token, is_read);

CREATE TABLE IF NOT EXISTS public.push_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_token text NOT NULL,
  endpoint text NOT NULL UNIQUE,
  p256dh_key text NOT NULL,
  auth_key text NOT NULL,
  created_at timestamptz DEFAULT now() NOT NULL,
  updated_at timestamptz DEFAULT now() NOT NULL
);

CREATE INDEX IF NOT EXISTS push_subscriptions_device_token_idx
  ON public.push_subscriptions (device_token);

ALTER TABLE public.notification_queue ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "device_token dapat melihat notifikasi miliknya"
  ON public.notification_queue
  FOR SELECT
  USING (true);

CREATE POLICY "device_token dapat menandai notifikasi dibaca"
  ON public.notification_queue
  FOR UPDATE
  USING (true)
  WITH CHECK (true);

CREATE POLICY "sistem dapat memasukkan notifikasi"
  ON public.notification_queue
  FOR INSERT
  WITH CHECK (true);

CREATE POLICY "device_token dapat melihat langganan push miliknya"
  ON public.push_subscriptions
  FOR SELECT
  USING (true);

CREATE POLICY "device_token dapat menyimpan langganan push"
  ON public.push_subscriptions
  FOR INSERT
  WITH CHECK (true);

CREATE POLICY "device_token dapat memperbarui langganan push"
  ON public.push_subscriptions
  FOR UPDATE
  USING (true);

CREATE POLICY "device_token dapat menghapus langganan push"
  ON public.push_subscriptions
  FOR DELETE
  USING (true);
